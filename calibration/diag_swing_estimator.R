# =====================================================================
# diag_swing_estimator.R -- IS THE MID-CENTURY PAUSE A FEATURE OR A SMOOTHER?
#
# handoff 21d sec.10 TEST 2 reported an ice-derived CO2 growth rate that
# "nearly halves in the 1950s (0.376 -> 0.207) and then jumps to 0.523", and
# read that localised pause as the crossover of the ~9 ppm level swing. That
# table set the next session's priority (sec.12c: go after the LUC time
# profile).
#
# TEST 2 estimated the ice growth rate by differentiating a
# loess(CO2ppm ~ year, span = 0.25) fitted over 1850-1996 -- an effective
# window of ~36 yr, i.e. WIDER THAN THE FEATURE IT IS RESOLVING. A smoother
# that wide cannot be assumed to preserve the decade of a decadal feature.
#
# FOUR GATES:
#   GATE 1 -- the same decadal growth rates from a raw within-decade OLS on the
#             samples, with no smoother anywhere. If the decade of the minimum
#             or its depth moves, TEST 2's localisation is the estimator.
#   GATE 2 -- the noise floor. Over the ice/SPO overlap, the same estimator on
#             both products. SPO is a flask record with no firn and no gas age,
#             so ice-minus-SPO on the SAME estimator is this record's own
#             decadal-growth error bar.
#   GATE 3 -- LIKE-FOR-LIKE. TEST 2 compared a SMOOTHED observation against an
#             UNSMOOTHED model. Here the model is sampled at the ice sample
#             years and run through the identical estimator.
#   GATE 4 -- GCB's OWN BUDGET IMBALANCE. GCB 2025 publishes `imbalance`, which
#             its header calls "a measure of our imperfect data and understanding
#             of the contemporary carbon cycle". If the model's growth-rate error
#             tracks it, the swing is inherited from the input rather than
#             generated by the model -- and the E_LUC-shape question in sec.12c
#             is already partly answered on disk.
#
# The regression in GATE 4 was first run against TEST 2's LOESS numbers and gave
# r = 0.839. GATE 1 puts those numbers in doubt, so it is re-run here on the raw
# estimator, which is the only version that should be quoted.
#
# Usage:  Rscript calibration/diag_swing_estimator.R
# =====================================================================
for (f in list.files("R", pattern = "[.]R$", full.names = TRUE)) source(f)
ccx_load_cpp()

SE_MODE_FILE <- file.path("calibration", "output", "pump_arms", "mode_fit_pumpN.rds")
SE_YEARS     <- c(1750, 2024)
SE_DECADES   <- seq(1870, 1970, 10)     # decades with enough ice samples to fit
SE_MIN_N     <- 5                       # samples required to fit a decade slope
SE_OVERLAP   <- c(1958, 2000)           # ice x SPO, for the noise floor
SE_PPM_PER_GTC <- 2.124                 # GtC per ppm (repo convention)

md <- readRDS(SE_MODE_FILE); pm <- md$par_mode
p <- ccx_default_params()
for (n in intersect(names(p), CCX_PARAM_NAMES)) p[[n]] <- pm[[n]]
p$pump_mode <- md$pump_mode
sp <- ccx_spinup(p)
F  <- ccx_build_forcing("historical", SE_YEARS, prod_c14 = sp$prod_c14,
                        bomb_total_kmol = pm$bomb_total, luc_scale = pm$luc_scale)
o  <- ccx_run_fast(sp, F)$out
mod_at <- function(yr) stats::approx(o$t, o$co2_SH, xout = yr, rule = 2)$y

obs <- ccx_prepare_obs()
ice <- as.data.frame(obs$ice)
spo <- as.data.frame(obs$co2_ann$SPO)

# ---- the estimator: raw OLS slope within a decade, no smoothing ------
dec_slope <- function(yr, v, dec, min_n = SE_MIN_N) {
  k <- yr >= dec & yr < dec + 10
  if (sum(k) < min_n) return(c(slope = NA, n = sum(k)))
  f <- stats::lm(v[k] ~ yr[k])
  c(slope = unname(stats::coef(f)[2]), n = sum(k))
}

cat(sprintf("mode %s   ice n=%d   SPO n=%d\n\n", basename(SE_MODE_FILE),
            nrow(ice), nrow(spo)))

# ---- GATE 1: raw estimator vs TEST 2's LOESS -------------------------
cat("GATE 1 -- decadal CO2 growth rate, ppm/yr: RAW within-decade OLS\n")
cat(sprintf("  %-8s %4s %9s %9s %9s\n", "decade", "n", "ice", "model", "mod-ice"))
tab <- data.frame()
for (d in SE_DECADES) {
  a <- dec_slope(ice$year, ice$CO2ppm, d)
  if (is.na(a["slope"])) { cat(sprintf("  %-8d %4d %9s\n", d, a["n"], "(too few)")); next }
  # LIKE-FOR-LIKE (GATE 3): model sampled at the SAME sample years, SAME estimator
  b <- dec_slope(ice$year, mod_at(ice$year), d)
  cat(sprintf("  %-8d %4d %+9.3f %+9.3f %+9.3f\n", d, a["n"], a["slope"], b["slope"],
              b["slope"] - a["slope"]))
  tab <- rbind(tab, data.frame(dec = d, n = a["n"], ice = a["slope"], mod = b["slope"],
                               err = b["slope"] - a["slope"]))
}
mn <- tab$dec[which.min(tab$ice)]
cat(sprintf("\n  minimum ice growth rate: %ds at %+.3f ppm/yr\n", mn, min(tab$ice)))
cat(sprintf("  TEST 2 (LOESS) reported the minimum in the 1950s at +0.207\n"))
cat(sprintf("  => %s\n\n", if (mn == 1950) "SAME decade" else
            sprintf("DIFFERENT decade -- TEST 2's localisation is the estimator")))

# ---- GATE 2: the noise floor, ice vs SPO on the same estimator -------
cat("GATE 2 -- decadal growth: ice vs SPO flask (no firn, no gas age), ppm/yr\n")
cat(sprintf("  %-8s %4s %9s %9s %9s\n", "decade", "n", "ice", "SPO", "ice-SPO"))
dif <- c()
for (d in seq(SE_OVERLAP[1] - SE_OVERLAP[1] %% 10, SE_OVERLAP[2] - 10, 10)) {
  a <- dec_slope(ice$year, ice$CO2ppm, d)
  b <- dec_slope(spo$year, spo$level, d)
  if (is.na(a["slope"]) || is.na(b["slope"])) next
  cat(sprintf("  %-8d %4d %+9.3f %+9.3f %+9.3f\n", d, a["n"], a["slope"], b["slope"],
              a["slope"] - b["slope"]))
  dif <- c(dif, a["slope"] - b["slope"])
}
floor_sd <- sqrt(mean(dif^2))
cat(sprintf("\n  RMS(ice - SPO) = %.3f ppm/yr  <- this record's decadal-growth error bar\n",
            floor_sd))
cat(sprintf("  depth of the raw pause below its neighbours: %.3f ppm/yr\n",
            mean(c(tab$ice[tab$dec == mn - 10], tab$ice[tab$dec == mn + 10])) - min(tab$ice)))
cat(sprintf("  => the pause is %.1f x the noise floor\n\n",
            (mean(c(tab$ice[tab$dec == mn - 10], tab$ice[tab$dec == mn + 10])) -
             min(tab$ice)) / floor_sd))

# ---- GATE 4: against GCB's own budget imbalance ----------------------
h <- as.data.frame(readRDS(file.path("data", "gcb_budget.rds"))$historical)
h$dec <- floor(h$year / 10) * 10
bim <- tapply(h$imbalance, h$dec, mean, na.rm = TRUE)
tab$bim <- as.numeric(bim[as.character(tab$dec)])
tab$err_gtc <- tab$err * SE_PPM_PER_GTC
k <- !is.na(tab$bim)
cat("GATE 4 -- model growth-rate error vs GCB's OWN budget imbalance\n")
cat(sprintf("  %-8s %11s %11s\n", "decade", "mod-ice", "GCB B_IM"))
for (i in which(k)) cat(sprintf("  %-8d %+11.3f %+11.3f\n", tab$dec[i], tab$err_gtc[i], tab$bim[i]))
if (sum(k) >= 3) {
  fit <- stats::lm(err_gtc ~ bim, data = tab[k, ])
  cat(sprintf("\n  n = %d decades   r = %.3f   slope %.3f   intercept %+.3f\n",
              sum(k), stats::cor(tab$err_gtc[k], tab$bim[k]),
              stats::coef(fit)[2], stats::coef(fit)[1]))
  cat(sprintf("  (TEST 2's LOESS numbers gave r = 0.839, slope 0.486)\n"))
}
cum <- sum(h$imbalance[h$year >= 1930 & h$year <= 1969], na.rm = TRUE)
cat(sprintf("\n  GCB cumulative imbalance 1930-1969: %+.1f GtC = %+.1f ppm\n",
            cum, cum / SE_PPM_PER_GTC))
cat(sprintf("  GCB imbalance 2015-2024:            %+.3f GtC/yr (i.e. the modern\n",
            mean(h$imbalance[h$year >= 2015], na.rm = TRUE)))
cat("    budget closes, so this explains the mid-century and NOT the land-sink miss)\n")
